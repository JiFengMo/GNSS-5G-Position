/* Optional end-to-end QA: PLAYWRIGHT_MODULE may point to an existing Playwright installation. */
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=process.argv[2] || 'http://127.0.0.1:8765';
const output=path.resolve('build/playwright');fs.mkdirSync(output,{recursive:true});
let activeBrowser;
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.BROWSER_PATH?{executablePath:process.env.BROWSER_PATH}:{})});
  activeBrowser=browser;
  const page=await browser.newPage({viewport:{width:1536,height:1080},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);await page.waitForSelector('#metric-cells');
  await page.waitForFunction(()=>document.querySelector('#disk-config').textContent.length>0);
  fs.writeFileSync(path.join(output,'initial.txt'),await page.locator('body').innerText());
  assert.equal(await page.locator('#metric-cells').innerText(),'0');
  await page.screenshot({path:path.join(output,'empty-summary.png'),fullPage:true});
  await page.getByRole('button',{name:'记录回看',exact:true}).click();
  const recordings=await (await page.request.get(base+'/api/recordings')).json();
  const demo=recordings.recordings.find(r=>r.config.demo);assert(demo,'Generate a demo recording first');
  await page.locator('#recording-select').selectOption(demo.file);
  await page.waitForFunction(()=>document.querySelector('#timeline').max==='99');
  await page.locator('#timeline').focus();await page.keyboard.press('End');
  assert.equal(await page.locator('#metric-cells').innerText(),'2');
  assert.match(await page.locator('#notice').innerText(),/非实测/);
  await page.screenshot({path:path.join(output,'summary.png'),fullPage:true});
  await page.locator('[data-page="trace"]').click();
  await page.locator('#cell-select').selectOption('3610000000:85:1');
  assert.match(await page.locator('#trace-caption').innerText(),/硬件采样计数/);
  const before=await page.locator('#chart-iq').evaluate(c=>c.toDataURL());
  const box=await page.locator('#chart-iq').boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.wheel(0,-600);
  const zoomed=await page.locator('#chart-iq').evaluate(c=>c.toDataURL());assert.notEqual(before,zoomed);
  await page.locator('#chart-iq').dblclick();
  await page.mouse.move(0,0);
  await page.screenshot({path:path.join(output,'trace.png'),fullPage:true});
  fs.writeFileSync(path.join(output,'trace.txt'),await page.locator('body').innerText());
  await page.locator('[data-page="results"]').click();
  await page.screenshot({path:path.join(output,'results.png'),fullPage:true});
  await page.getByRole('button',{name:'TOA 与距离',exact:true}).click();
  assert.match(await page.locator('#toa-table').innerText(),/满足已声明/);
  await page.getByRole('button',{name:/位置坐标/}).click();
  assert.match(await page.locator('#position-result').innerText(),/xyz_m: null/);
  await page.screenshot({path:path.join(output,'position-reserved.png'),fullPage:true});
  const previousPosition=await page.locator('#replay-position').innerText();
  await page.locator('#page-next').click();
  await page.waitForFunction(previous=>document.querySelector('#replay-position').textContent!==previous,previousPosition);
  await page.locator('#timeline').focus();await page.keyboard.press('End');
  await page.locator('[data-page="summary"]').click();
  assert.match(await page.locator('#cell-table').innerText(),/候选 \/ 未锁定/);
  // Returning to the previous page preserves cursor boundaries without IQ recomputation.
  await page.locator('#page-prev').click();
  await page.waitForFunction(()=>document.querySelector('#timeline').value==='0');
  await page.locator('#play').click();await page.waitForFunction(()=>Number(document.querySelector('#timeline').value)>0);
  await page.locator('#play').click();
  // Inject explicitly labelled synthetic live responses only into this test browser.
  let requests=0,timeModel='shared',calibrated=true;
  const meta=demo.config;
  const sample={schema:1,kind:'sample',run_id:meta.run_id,time_ms:Date.now(),seq:1,event_id:'test-live',freq_hz:3600000000,pci:84,ssb:0,locked:true,mib_ok:true,pbch_ok:true,cfo_hz:100,snr_db:20,pss_metric:10,relative_delay_ns:125,clock_locked:true,absolute_candidate_valid:true,toa_candidate_ns:100,cell_key:'3600000000:84:0'};
  await page.route('**/api/state?*',async route=>{requests++;const now=Date.now();await route.fulfill({json:{run_id:meta.run_id,now_ms:now,config:{...meta,time_model:timeModel,absolute_toa_calibrated:calibrated},runtime:{kind:'runtime',time_ms:now,state:3,sample_rate_hz:30720000,clock_locked:true},cells:[{...sample,time_ms:now}],trace:null,series:[sample],selected:sample.cell_key,connected:true}});});
  await page.getByRole('button',{name:'实时监看',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#connection-label').textContent==='数据已连接');
  await page.locator('#freeze').click();
  const frozen=requests;await page.waitForTimeout(600);assert.equal(requests,frozen);
  assert.match(await page.locator('#notice').innerText(),/非实测|冻结/);
  await page.locator('#freeze').click();await page.waitForFunction(()=>document.querySelector('#connection-label').textContent==='数据已连接');
  assert(requests>frozen);
  await page.locator('[data-page="results"]').click();
  await page.getByRole('button',{name:'TOA 与距离',exact:true}).click();
  timeModel='receiver_bias';await page.waitForFunction(()=>document.querySelector('#toa-table').textContent.includes('接收机含钟差'));
  assert.doesNotMatch(await page.locator('#toa-table').innerText(),/29\.979/);
  timeModel='shared';calibrated=false;await page.waitForFunction(()=>document.querySelector('#toa-table').textContent.includes('标定未确认'));
  await page.unroute('**/api/state?*');
  await page.setViewportSize({width:800,height:1000});
  await page.screenshot({path:path.join(output,'compact.png'),fullPage:true});
  assert.deepEqual(errors,[],'Browser errors');
  console.log('PASS: pages, per-cell trace, zoom, replay pagination/playback, loss of lock, TOA validity, reserved position and freeze/resume');
  await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{if(activeBrowser)await activeBrowser.close();});
